#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Convert a DAPLink target family dir into this project's target_<short>.c/.h.

DAPLink target layout (source/family/<vendor>/<chip>/):
    flash_blob.c : blob array + sectors_info[] + `program_target_t flash`
    target.c     : target_cfg_t with flash/ram regions, vendor, part number

This project uses the same program_target_t / sector_info_t (see flash_blob.h),
so the blob is copied verbatim and only `flash` / `sectors_info` are renamed and
wrapped in a `target_cfg_t`.

Usage:
    python tools/port_family.py <daplink_chip_dir> <short_name> [out_dir]
"""

import os
import re
import sys

KBL = re.compile(r'\bKB\(([^)]*)\)')
MBL = re.compile(r'\bMB\(([^)]*)\)')


def ev(expr):
    expr = re.sub(r'//.*', '', expr).strip().rstrip(',')
    expr = KBL.sub(r'(\1*1024)', expr)
    expr = MBL.sub(r'(\1*1024*1024)', expr)
    return int(eval(expr, {"__builtins__": {}}, {}))


def block(text, start_re):
    m = re.search(start_re, text, re.S)
    if not m:
        return None, None
    name = m.group(1) if m.groups() else None
    i = text.index('{', m.start())
    depth = 0
    for j in range(i, len(text)):
        if text[j] == '{':
            depth += 1
        elif text[j] == '}':
            depth -= 1
            if depth == 0:
                return name, text[m.start():j + 1] + ";"
    return name, None


def main():
    chip_dir, short = sys.argv[1], sys.argv[2]
    out_dir = sys.argv[3] if len(sys.argv) > 3 else os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "flash")

    blob_src = open(os.path.join(chip_dir, "flash_blob.c"), encoding="utf-8").read()
    tgt_src = open(os.path.join(chip_dir, "target.c"), encoding="utf-8").read()

    blob_name, blob_body = block(blob_src, r'static const uint32_t (\w+)\[\]')
    _, sectors_body = block(blob_src, r'static const sector_info_t sectors_info\[\]')
    _, flash_body = block(blob_src, r'static const program_target_t flash\b')
    if not (blob_name and blob_body and sectors_body and flash_body):
        print("parse failure"); sys.exit(1)

    # target.c fields
    def field(pat, default="0"):
        m = re.search(pat, tgt_src)
        return ev(m.group(1)) if m else default
    fs = field(r'flash_regions\[0\]\.start\s*=\s*([^,]+)')
    fe = field(r'flash_regions\[0\]\.end\s*=\s*([^,]+)')
    r0s = field(r'ram_regions\[0\]\.start\s*=\s*([^,]+)')
    r0e = field(r'ram_regions\[0\]\.end\s*=\s*([^,]+)')
    r1s = re.search(r'ram_regions\[1\]\.start\s*=\s*([^,]+)', tgt_src)
    r1e = re.search(r'ram_regions\[1\]\.end\s*=\s*([^,]+)', tgt_src)
    vendor = re.search(r'target_vendor\s*=\s*"([^"]*)"', tgt_src).group(1)
    part = re.search(r'target_part_number\s*=\s*"([^"]*)"', tgt_src).group(1)

    flash_body = flash_body.replace('{', '{', 1)
    header = ("/*\n * SPDX-License-Identifier: Apache-2.0\n *\n"
              " * %s target configuration and flash algorithm.\n"
              " * Auto-ported from DAPLink %s by tools/port_family.py\n */\n\n"
              "#include \"flash_blob.h\"\n" % (part, os.path.relpath(chip_dir).replace("\\", "/")))

    sec_braces = sectors_body[sectors_body.index('{'):]
    sectors = "static const sector_info_t %s_sectors_info[] = %s\n" % (short, sec_braces)
    pt = flash_body.replace("program_target_t flash =", "program_target_t %s_flash =" % short)

    ram1 = ""
    if r1s and r1e:
        ram1 = ("\t.ram_regions[1]     = { .start = 0x%08X, .end = 0x%08X },\n"
                % (ev(r1s.group(1)), ev(r1e.group(1))))

    cfg = ("\nconst target_cfg_t target_%s = {\n"
           "\t.sectors_info       = %s_sectors_info,\n"
           "\t.sector_info_length = sizeof(%s_sectors_info) / sizeof(sector_info_t),\n"
           "\t.flash_regions[0]   = {\n"
           "\t\t.start      = 0x%08X,\n\t\t.end        = 0x%08X,\n"
           "\t\t.flags      = REGION_IS_DEFAULT,\n\t\t.flash_algo = &%s_flash,\n\t},\n"
           "\t.ram_regions[0]     = { .start = 0x%08X, .end = 0x%08X },\n"
           "%s"
           "\t.target_vendor     = \"%s\",\n"
           "\t.target_part_number = \"%s\",\n};\n"
           % (short, short, short, fs, fe, short, r0s, r0e, ram1, vendor, part))

    os.makedirs(out_dir, exist_ok=True)
    open(os.path.join(out_dir, "target_%s.c" % short), "w", encoding="utf-8").write(
        header + "\n" + blob_body + "\n\n" + sectors + "\n" + pt + "\n" + cfg)
    guard = "TARGET_%s_H_" % short.upper().replace("-", "_")
    open(os.path.join(out_dir, "target_%s.h" % short), "w", encoding="utf-8").write(
        "/* SPDX-License-Identifier: Apache-2.0 - auto-generated by tools/port_family.py */\n"
        "#ifndef %s\n#define %s\n\n#include \"flash_blob.h\"\n\n"
        "extern const target_cfg_t target_%s;\n\n#endif\n" % (guard, guard, short))
    print("generated target_%s.c/.h  (%s, flash 0x%08X-0x%08X)" % (short, part, fs, fe))


if __name__ == "__main__":
    main()
